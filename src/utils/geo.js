/**
 * 繁体地名 → 简体。不认识的字原样保留。
 * @param {string} name
 */
export function toSimplified(name) {
  if (!name) return ''
  let out = ''
  for (const ch of String(name)) out += TRAD_TO_SIMP[ch] || ch
  return out
}

/**
 * 从 BigDataCloud 的响应里挑一个城市名。
 *
 * 顺序与参考站不同（参考站是 locality 优先，会给出「黃浦區」这种区级名，
 * 而且带繁体）。这里改成 city 优先，拿到的多是「上海市」这种市级名，
 * 与设置面板里「城市」的语义一致，也更好看。
 *
 * @param {object} d BigDataCloud reverse-geocode-client 的响应
 */
export function pickCityName(d) {
  const raw =
    d?.city || d?.locality || d?.principalSubdivision || d?.countryName || ''
  return toSimplified(raw).trim()
}

/**
 * 从 Nominatim 的 address 对象里挑一个城市名。Nominatim 兜底用。
 * @param {object} d Nominatim /reverse 的响应
 */
export function pickNominatimCity(d) {
  const a = d?.address || {}
  const raw =
    a.city ||
    a.town ||
    a.county ||
    a.village ||
    a.suburb ||
    a.state_district ||
    a.state ||
    a.region ||
    a.country ||
    d?.name ||
    (d?.display_name ? String(d.display_name).split(',')[0] : '')
  return toSimplified(raw).trim()
}
